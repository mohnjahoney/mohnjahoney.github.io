import { writeFile } from "node:fs/promises";
import {
  createHexagonPath,
  createMOutlinePoints,
  type Point,
} from "../src/components/mHexGeometry.ts";

const format = (value: number): string => Number(value.toFixed(4)).toString();
const toSvgPath = (points: readonly Point[]): string =>
  points.map(({ x, y }, index) => `${index === 0 ? "M" : "L"}${format(x)} ${format(y)}`).join(" ") +
  " Z";

const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 128 128" role="img" aria-labelledby="m-hex-mark-title m-hex-mark-desc">
  <title id="m-hex-mark-title">M hex monogram</title>
  <desc id="m-hex-mark-desc">A cyan regular hexagon carrying an off-white filled M contour.</desc>
  <!-- Generated by scripts/generate-m-hex-mark.ts. Edit mHexGeometry.ts instead. -->
  <path d="${createHexagonPath()}" fill="#0d9fd1"/>
  <path d="${toSvgPath(createMOutlinePoints())}" fill="#f7f5ef"/>
</svg>
`;

await writeFile(new URL("../public/m-hex-mark.svg", import.meta.url), svg);
