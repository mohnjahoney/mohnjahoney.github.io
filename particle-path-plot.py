"""Draw and animate a family of trajectories on a rotational surface.

The surface is made by rotating a 2D radius profile around the x axis. A
trajectory is parameterized by x=t and an angle theta(t), so its 3D position
is (x, y, z) = (t, radius(t) * cos(theta(t)), radius(t) * sin(theta(t))).

Examples:
    python particle-path-plot.py
    python particle-path-plot.py --animate
    python particle-path-plot.py --animate --save trajectories.mp4
    uv run --with matplotlib --with numpy particle-path-plot.py --animate
"""

from __future__ import annotations

import argparse
from dataclasses import dataclass

import matplotlib.pyplot as plt
import numpy as np
from matplotlib.animation import FuncAnimation, PillowWriter


@dataclass(frozen=True)
class Settings:
    paths: int = 28
    samples: int = 700
    turns: float = 4.0
    radius_scale: float = 1.0


def radius_profile(t: np.ndarray, scale: float = 1.0) -> np.ndarray:
    """A tapered three-bump profile, zero at both endpoints."""
    t = np.asarray(t)
    envelope = np.sin(np.pi * t) ** 0.72
    bumps = (
        0.88 * np.exp(-((t - 0.20) / 0.16) ** 2)
        + 0.43 * np.exp(-((t - 0.49) / 0.095) ** 2)
        + 0.62 * np.exp(-((t - 0.72) / 0.105) ** 2)
    )
    return scale * envelope * bumps


def theta_profile(t: np.ndarray, path_index: int, settings: Settings) -> np.ndarray:
    """Give each path a slightly different winding while keeping endpoints fixed."""
    phase = 2 * np.pi * path_index / settings.paths
    turns = settings.turns + 0.28 * np.sin(2 * np.pi * path_index / settings.paths)
    easing = t + 0.10 * np.sin(2 * np.pi * t) * t * (1 - t)
    return phase + 2 * np.pi * turns * easing


def trajectory(path_index: int, t: np.ndarray, settings: Settings):
    """Return x, y, z samples for one trajectory."""
    radius = radius_profile(t, settings.radius_scale)
    theta = theta_profile(t, path_index, settings)
    return t, radius * np.cos(theta), radius * np.sin(theta)


def make_axes():
    fig = plt.figure(figsize=(11, 8), facecolor="#0d1117")
    ax = fig.add_subplot(111, projection="3d", facecolor="#0d1117")
    ax.set_xlabel("x", color="#d7dee8", labelpad=10)
    ax.set_ylabel("y", color="#d7dee8", labelpad=10)
    ax.set_zlabel("z", color="#d7dee8", labelpad=10)
    ax.tick_params(colors="#9da9b8")
    ax.set_xlim(0, 1)
    ax.set_ylim(-1.15, 1.15)
    ax.set_zlim(-1.15, 1.15)
    ax.set_box_aspect((1.35, 1, 1))
    ax.grid(False)
    for pane in (ax.xaxis.pane, ax.yaxis.pane, ax.zaxis.pane):
        pane.set_facecolor((0.05, 0.07, 0.10, 1))
        pane.set_edgecolor((0.18, 0.22, 0.28, 1))
    return fig, ax


def add_surface(ax, settings: Settings):
    """Add a translucent surface generated by rotating the profile."""
    x = np.linspace(0, 1, 170)
    angles = np.linspace(0, 2 * np.pi, 50)
    xx, aa = np.meshgrid(x, angles)
    rr = radius_profile(xx, settings.radius_scale)
    yy, zz = rr * np.cos(aa), rr * np.sin(aa)
    ax.plot_surface(
        xx, yy, zz, color="#477b9e", alpha=0.075,
        linewidth=0, antialiased=True, shade=False,
    )


def draw_static(settings: Settings, show_surface: bool):
    fig, ax = make_axes()
    if show_surface:
        add_surface(ax, settings)

    t = np.linspace(0, 1, settings.samples)
    colors = plt.cm.turbo(np.linspace(0.08, 0.92, settings.paths))
    for i, color in enumerate(colors):
        x, y, z = trajectory(i, t, settings)
        ax.plot(x, y, z, color=color, linewidth=1.5, alpha=0.92)

    ax.scatter([0, 1], [0, 0], [0, 0], color="#f7f2d0", s=35, depthshade=False)
    ax.text(0, 0, 0.08, "A", color="#f7f2d0", ha="center")
    ax.text(1, 0, 0.08, "B", color="#f7f2d0", ha="center")
    ax.set_title("A collection of trajectories on a 3D surface", color="#f7f2d0", pad=18)
    return fig


def animate(settings: Settings, show_surface: bool, save_path: str | None):
    fig, ax = make_axes()
    if show_surface:
        add_surface(ax, settings)

    t = np.linspace(0, 1, settings.samples)
    colors = plt.cm.turbo(np.linspace(0.08, 0.92, settings.paths))
    trajectories = [trajectory(i, t, settings) for i in range(settings.paths)]
    lines = [ax.plot([], [], [], color=color, linewidth=1.35, alpha=0.76)[0] for color in colors]
    # Initialize with one marker per color. Matplotlib 3D scatter rejects an
    # empty point set when the color array already contains all path colors.
    initial_locations = np.array([(x[0], y[0], z[0]) for x, y, z in trajectories])
    points = ax.scatter(
        initial_locations[:, 0],
        initial_locations[:, 1],
        initial_locations[:, 2],
        c=colors,
        s=34,
        depthshade=False,
    )
    ax.scatter([0, 1], [0, 0], [0, 0], color="#f7f2d0", s=35, depthshade=False)
    ax.text(0, 0, 0.08, "A", color="#f7f2d0", ha="center")
    ax.text(1, 0, 0.08, "B", color="#f7f2d0", ha="center")
    ax.set_title("Particles moving together from A to B", color="#f7f2d0", pad=18)

    def update(frame: int):
        progress = frame / (settings.samples - 1)
        visible = max(2, int(progress * (settings.samples - 1)))
        locations = []
        for line, (x, y, z) in zip(lines, trajectories):
            line.set_data(x[:visible], y[:visible])
            line.set_3d_properties(z[:visible])
            locations.append((x[visible - 1], y[visible - 1], z[visible - 1]))
        points._offsets3d = tuple(np.asarray(locations).T)
        return [*lines, points]

    animation = FuncAnimation(fig, update, frames=settings.samples, interval=20, blit=False)
    if save_path:
        if save_path.lower().endswith(".gif"):
            animation.save(save_path, writer=PillowWriter(fps=40), dpi=120)
        else:
            animation.save(save_path, fps=40, dpi=120)
        print(f"Saved animation to {save_path}")
    return fig, animation


def parse_args():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--animate", action="store_true", help="animate particles along all paths")
    parser.add_argument("--save", metavar="FILE", help="save animation as .gif or .mp4")
    parser.add_argument("--paths", type=int, default=Settings.paths, help="number of trajectories")
    parser.add_argument("--turns", type=float, default=Settings.turns, help="average number of turns")
    parser.add_argument("--no-surface", action="store_true", help="hide the translucent generated surface")
    return parser.parse_args()


if __name__ == "__main__":
    args = parse_args()
    settings = Settings(paths=max(1, args.paths), turns=args.turns)
    if args.animate or args.save:
        # Keep the animation alive until the GUI event loop starts. Without
        # this reference Matplotlib may garbage-collect it before rendering.
        animation = animate(settings, not args.no_surface, args.save)
    else:
        draw_static(settings, not args.no_surface)
    plt.show()
